"""ASC(Vector ASCII) 로그 리더/라이터 (Phase 3).

원본: `Format Converter/AscLogConverter` (lex/yacc 기반).
여기서는 표준 Vector ASC 포맷의 클래식 CAN 데이터 프레임을 직접 파싱한다.

지원하는 줄 형식:
    <time> <channel> <id> <Rx|Tx> d <dlc> <byte...>
    <time> <channel> <id> <Rx|Tx> fd <dlc> <byte...>   (CAN FD, 플래그 생략형)

헤더 줄(`date`, `base`, `//` 주석, 빈 줄)은 건너뛴다.
"""

from __future__ import annotations

import datetime as _dt
import re

from bsmaster.logconv.frames import LogFrame

_ASC_RE = re.compile(
    r"^\s*(\d+(?:\.\d+)?)\s+"      # timestamp
    r"(\d+)\s+"                    # channel
    r"([0-9A-Fa-f]+)[xX]?\s+"      # id (확장 ID는 'x' 접미사 가능)
    r"(Rx|Tx)\s+"                  # 방향
    r"d\s+"                        # 데이터 프레임
    r"(\d+)"                       # DLC
    r"((?:\s+[0-9A-Fa-f]{2})*)"    # 데이터 바이트들
    r"\s*$"
)

_ASC_FD_RE = re.compile(
    r"^\s*(\d+(?:\.\d+)?)\s+"
    r"(\d+)\s+"
    r"([0-9A-Fa-f]+)[xX]?\s+"
    r"(Rx|Tx)\s+"
    r"fd\s+"
    r"(?:\d+\s+)?"                 # BRS/ESI 플래그 (있을 수도 있음)
    r"(\d+)"
    r"((?:\s+[0-9A-Fa-f]{2})*)"
    r"\s*$"
)


def _parse_id(raw: str) -> tuple[int, bool]:
    msg_id = int(raw, 16)
    return msg_id, msg_id > 0x7FF


def parse_line(line: str) -> LogFrame | None:
    """ASC 한 줄을 파싱. 프레임이 아니면 None."""
    m = _ASC_RE.match(line)
    if m is not None:
        is_canfd = False
    else:
        m = _ASC_FD_RE.match(line)
        if m is None:
            return None
        is_canfd = True
    ts_s, ch_s, id_s, direction, dlc_s, data_s = m.groups()
    msg_id, extended = _parse_id(id_s)
    data = bytes(int(b, 16) for b in data_s.split())
    dlc = int(dlc_s)
    data = data[:dlc]
    return LogFrame(
        timestamp=float(ts_s),
        channel=int(ch_s),
        msg_id=msg_id,
        extended=extended,
        direction=direction,
        data=data,
        is_canfd=is_canfd,
    )


def read_asc(path: str) -> list[LogFrame]:
    """ASC 파일을 읽어 `LogFrame` 리스트 반환."""
    frames: list[LogFrame] = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            frame = parse_line(line)
            if frame is not None:
                frames.append(frame)
    return frames


def _format_line(frame: LogFrame) -> str:
    data_hex = " ".join(f"{b:02X}" for b in frame.data)
    kind = "fd" if frame.is_canfd else "d"
    return (
        f"{frame.timestamp:12.6f} {frame.channel}  {frame.msg_id:X}  "
        f"{frame.direction}   {kind} {len(frame.data)} {data_hex}".rstrip()
        + "\n"
    )


def write_asc(path: str, frames: list[LogFrame]) -> None:
    """`LogFrame` 리스트를 ASC 파일로 저장."""
    now = _dt.datetime.now().strftime("%a %b %d %H:%M:%S %Y")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"date {now}\n")
        f.write("base hex  timestamps absolute\n")
        f.write("internal events logged\n")
        f.write("// generated by bsmaster\n")
        for frame in frames:
            f.write(_format_line(frame))
